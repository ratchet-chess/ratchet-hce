/**
 * Writes core/bench-fens.ts: the FENs of bench/positions.txt as one static string,
 * for the WASI build's `bench` command, which has no filesystem to read the file
 * from. tools/build.sh runs it before compiling, so the two never differ.
 *
 *   bun tools/bench-fens.ts
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const fens = readFileSync(`${root}bench/positions.txt`, "utf8")
  .trim()
  .split("\n")
  .map((line) => line.slice(line.indexOf("|") + 1).trim());
// one literal, because a concatenation would run when the module starts and the stub runtime never frees its parts
writeFileSync(
  `${root}core/bench-fens.ts`,
  `// Generated by tools/bench-fens.ts from bench/positions.txt; do not edit.\n` +
    `/** the bench set's FENs, one per line, in bench/positions.txt's order */\n` +
    `export const BENCH_FENS = ${JSON.stringify(fens.join("\n"))};\n`,
);
