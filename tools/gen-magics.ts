/**
 * Writes core/magics.ts: the magic multipliers the core's seeded
 * search finds, so startup can verify them instead of searching.
 *
 *   bun run build:wasm && bun tools/gen-magics.ts && bun run build:wasm
 */
import { readFileSync, writeFileSync } from "node:fs";

const bytes = readFileSync(new URL("../build/core.wasm", import.meta.url));
const { instance } = await WebAssembly.instantiate(bytes, {
  env: {
    abort: () => {
      throw new Error("abort");
    },
    poll: () => 0,
  },
});
const w = instance.exports as unknown as { initCore(): void; magicNumber(k: number): bigint };
w.initCore();
const hex = Array.from(
  { length: 128 },
  (_, k) => "0x" + BigInt.asUintN(64, w.magicNumber(k)).toString(16).padStart(16, "0"),
);
const rows: string[] = [];
for (let i = 0; i < 128; i += 4) rows.push("  " + hex.slice(i, i + 4).join(", ") + ",");
writeFileSync(
  new URL("../core/magics.ts", import.meta.url),
  `// Generated by tools/gen-magics.ts. Do not edit.
// Magic multipliers per record (rooks 0..63, bishops 64..127). initTables() verifies
// each one and falls back to searching, so a stale entry costs time, not correctness.
export const KNOWN_MAGICS: StaticArray<u64> = [
${rows.join("\n")}
];
`,
);
console.log("wrote core/magics.ts");
